/**
 * Checks the translations. Run: npm run check:i18n -w @oracle/mobile
 *  - finds every t("...") sentence in src (and the ones listed in src/i18n/extra-keys.ts for text picked at run time),
 *  - checks every language file has all of them, with the same {placeholders},
 *  - warns about translations nobody uses.
 * `--write-keys` also writes src/i18n/keys.json, the list translators work from.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const root = new URL("../src", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const LANGS = ["id", "de", "fr", "es", "pt", "ru", "zh"];

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return f === "dictionaries" ? [] : walk(p);
    return /\.(tsx?|ts)$/.test(f) ? [p] : [];
  });
}
const unescape = (s) => s.replace(/\\(["'`\\])/g, "$1").replace(/\\n/g, "\n");
const keys = new Set();
const call = /(?<![\w.])t\(\s*(?:"((?:\\.|[^"\\])*)"|'((?:\\.|[^'\\])*)'|`((?:\\.|[^`\\$])*)`)/g;
for (const file of walk(root)) {
  // Comments may show example calls. Only real code counts.
  const src = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
  if (file.endsWith("extra-keys.ts")) {
    for (const m of src.matchAll(/"((?:\\.|[^"\\])*)"/g)) keys.add(unescape(m[1]));
    continue;
  }
  for (const m of src.matchAll(call)) keys.add(unescape(m[1] ?? m[2] ?? m[3]));
}
// The names of screens and buttons the assistant's app guide mentions are real sentences of the app too.
const guideFile = join(root, "..", "..", "shared", "core", "src", "app-guide.ts");
const guideLabels = [...new Set([...readFileSync(guideFile, "utf8").matchAll(/\[\[([^\]]+)\]\]/g)].map((m) => m[1]))].sort();
for (const l of guideLabels) keys.add(l);
keys.delete("");
const list = [...keys].sort((a, b) => a.localeCompare(b));
const dictionaries = {};
const holes = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(",");

let problems = 0;
for (const lang of LANGS) {
  const mod = await import(pathToFileURL(join(root, "i18n", "dictionaries", `${lang}.ts`)).href).catch(async () => null);
  const text = readFileSync(join(root, "i18n", "dictionaries", `${lang}.ts`), "utf8");
  // Read the dictionary by evaluating its object literal, without a TypeScript build.
  const body = text.slice(text.indexOf("{", text.indexOf("=")), text.lastIndexOf("}") + 1);
  const dict = new Function(`return (${body})`)();
  void mod;
  dictionaries[lang] = dict;
  const missing = list.filter((k) => !(k in dict));
  const wrong = list.filter((k) => k in dict && holes(k) !== holes(dict[k]));
  const empty = list.filter((k) => k in dict && !String(dict[k]).trim());
  const unused = Object.keys(dict).filter((k) => !keys.has(k));
  console.log(`${lang}: ${list.length - missing.length}/${list.length} translated${wrong.length ? `, ${wrong.length} with wrong placeholders` : ""}${unused.length ? `, ${unused.length} unused` : ""}`);
  for (const k of missing.slice(0, 8)) console.log(`   missing: ${k}`);
  for (const k of wrong.slice(0, 8)) console.log(`   placeholders differ: ${k}`);
  for (const k of empty.slice(0, 8)) console.log(`   empty: ${k}`);
  problems += missing.length + wrong.length + empty.length;
}
// shared/core/src/guide-labels.ts: the guide's labels in every language, taken from the app's own translations.
const generated = `// Generated by \`npm run check:i18n -w @oracle/mobile -- --write-guide\`. Do not edit by hand.
import type { LanguageCode } from "./constants";

export const GUIDE_LABELS: Partial<Record<LanguageCode, Record<string, string>>> = ${JSON.stringify(Object.fromEntries(LANGS.map((l) => [l, Object.fromEntries(guideLabels.map((k) => [k, dictionaries[l][k] ?? k]))])), null, 2)};
`;
const guideOut = join(root, "..", "..", "shared", "core", "src", "guide-labels.ts");
if (process.argv.includes("--write-guide")) {
  writeFileSync(guideOut, generated);
  console.log(`wrote ${guideLabels.length} guide labels to shared/core/src/guide-labels.ts`);
} else if (readFileSync(guideOut, "utf8").replace(/\r\n/g, "\n") !== generated) {
  console.log("shared/core/src/guide-labels.ts is out of date. Run: npm run check:i18n -w @oracle/mobile -- --write-guide");
  problems += 1;
}
if (process.argv.includes("--write-keys")) {
  writeFileSync(join(root, "i18n", "keys.json"), JSON.stringify(list, null, 2) + "\n");
  console.log(`wrote ${list.length} keys to src/i18n/keys.json`);
}
console.log(problems ? `\n${problems} problem(s)` : `\nall ${list.length} sentences are translated`);
process.exit(problems ? 1 : 0);
